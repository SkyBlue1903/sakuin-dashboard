-- 1. Buat Tabel public.promos
CREATE TABLE IF NOT EXISTS public.promos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  banner_url TEXT NOT NULL,
  banner_link TEXT DEFAULT NULL,
  short_description TEXT NOT NULL,
  content_html TEXT NOT NULL,
  published_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  takedown_at TIMESTAMPTZ DEFAULT NULL,
  is_hidden BOOLEAN NOT NULL DEFAULT false,
  is_highlight BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2. Index untuk Performa Query & Filter
CREATE INDEX IF NOT EXISTS idx_promos_created_at ON public.promos(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_promos_published_at ON public.promos(published_at DESC);
CREATE INDEX IF NOT EXISTS idx_promos_takedown_at ON public.promos(takedown_at DESC);
CREATE INDEX IF NOT EXISTS idx_promos_is_hidden ON public.promos(is_hidden);
CREATE INDEX IF NOT EXISTS idx_promos_is_highlight ON public.promos(is_highlight);

-- 3. Row Level Security (RLS) & Policies
ALTER TABLE public.promos ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public select promos" ON public.promos FOR SELECT USING (true);
CREATE POLICY "Public insert promos" ON public.promos FOR INSERT WITH CHECK (true);
CREATE POLICY "Public update promos" ON public.promos FOR UPDATE USING (true);
CREATE POLICY "Public delete promos" ON public.promos FOR DELETE USING (true);

-- 4. Sinkronisasi Identity Sequence agar ID baru selalu urut dan tidak duplikat
SELECT setval(
  pg_get_serial_sequence('public.promos', 'id'),
  COALESCE((SELECT max(id) FROM public.promos), 1),
  (SELECT count(*) > 0 FROM public.promos)
);
