-- 1. Buat Tabel public.infos
CREATE TABLE IF NOT EXISTS public.infos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  banner_url TEXT NOT NULL,
  banner_link TEXT DEFAULT NULL,
  short_description TEXT NOT NULL,
  content_html TEXT NOT NULL,
  published_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  is_hidden BOOLEAN NOT NULL DEFAULT false,
  is_highlight BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2. Index untuk Performa Query & Filter
CREATE INDEX IF NOT EXISTS idx_infos_created_at ON public.infos(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_infos_published_at ON public.infos(published_at DESC);
CREATE INDEX IF NOT EXISTS idx_infos_is_hidden ON public.infos(is_hidden);
CREATE INDEX IF NOT EXISTS idx_infos_is_highlight ON public.infos(is_highlight);

-- 3. Row Level Security (RLS) & Policies
ALTER TABLE public.infos ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public select infos" ON public.infos FOR SELECT USING (true);
CREATE POLICY "Public insert infos" ON public.infos FOR INSERT WITH CHECK (true);
CREATE POLICY "Public update infos" ON public.infos FOR UPDATE USING (true);
CREATE POLICY "Public delete infos" ON public.infos FOR DELETE USING (true);

-- 4. Sinkronisasi Identity Sequence agar ID baru selalu mulai dari urutan yang tepat
SELECT setval(
  pg_get_serial_sequence('public.infos', 'id'),
  COALESCE((SELECT max(id) FROM public.infos), 1),
  (SELECT count(*) > 0 FROM public.infos)
);
